// Builds supabase/seed.sql from the scripture catalogue and content/cards.*.json.
// Run: node scripts/build-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url).pathname;
const catalogue = JSON.parse(readFileSync(root + "content/catalogue.json", "utf8"));
const cards = readdirSync(root + "content")
  .filter((f) => f.startsWith("cards.") && f.endsWith(".json"))
  .flatMap((f) => JSON.parse(readFileSync(root + "content/" + f, "utf8")));

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(", ")}]::text[]`;
const out = ["-- Generated by scripts/build-seed.mjs. Do not edit by hand.", "begin;", ""];

for (const s of catalogue.sources)
  out.push(`insert into sources (id, title, author, year, url, licence, notes) values (${[s.id, s.title, s.author, s.year, s.url, s.licence, s.notes].map(q).join(", ")});`);
out.push("");
catalogue.scriptures.forEach((s, i) =>
  out.push(`insert into scriptures (id, name, name_sanskrit, category, parent_id, description, level_names, expected_verses, sort_order) values (${[s.id, s.name, s.name_sanskrit, s.category, s.parent_id, s.description].map(q).join(", ")}, ${arr(s.level_names)}, ${q(s.expected_verses)}, ${i});`)
);
out.push("");
for (const sec of catalogue.sections)
  out.push(`insert into sections (scripture_id, level, number, title, title_sanskrit, expected_verses) values (${[sec.scripture_id, 1, sec.number, sec.title, sec.title_sanskrit, sec.expected_verses].map(q).join(", ")});`);
out.push("");

// Where each card sits: scripture, top-level section number, verse number, sort key.
function place(c) {
  const n = c.id.split("-").filter((x) => /^\d+$/.test(x)).map(Number);
  if (c.id.startsWith("gita-")) return { scripture: "bhagavad-gita", section: n[0], number: n[1], sort: n[0] * 1000 + n[1] };
  if (c.id.startsWith("rv-")) return { scripture: "rig-veda", section: n[0], number: n[2], sort: n[0] * 1e6 + n[1] * 1000 + n[2] };
  if (c.id.startsWith("av-")) return { scripture: "atharva-veda", section: n[0], number: n[2], sort: n[0] * 1e6 + n[1] * 1000 + n[2] };
  if (c.id.startsWith("isha-")) return { scripture: "isha-upanishad", section: null, number: n[0], sort: n[0] };
  if (c.id.startsWith("brihadaranyaka-")) return { scripture: "brihadaranyaka-upanishad", section: n[0], number: n[2], sort: n[0] * 1e6 + n[1] * 1000 + n[2] };
  if (c.id === "taittiriya-shanti") return { scripture: "taittiriya-upanishad", section: null, number: 0, sort: 0 };
  throw new Error("No placement rule for " + c.id);
}

const tags = new Map();
for (const c of cards) {
  const p = place(c);
  const section = p.section == null ? "null" : `(select id from sections where scripture_id = ${q(p.scripture)} and level = 1 and number = ${p.section})`;
  out.push(`-- ${c.scripture}, ${c.reference}`);
  out.push(`insert into verses (id, scripture_id, section_id, number, reference, sanskrit, transliteration, sort_key, is_featured, source_id, status) values (${q(c.id)}, ${q(p.scripture)}, ${section}, ${q(p.number)}, ${q(c.reference)}, ${q(c.sanskrit)}, ${q(c.transliteration)}, ${p.sort}, true, 'public-domain-sanskrit', 'published');`);
  out.push(`insert into translations (verse_id, language, text, source_id, is_primary) values (${q(c.id)}, 'en', ${q(c.translation)}, 'veda-app-original', true);`);
  out.push(`insert into explanations (verse_id, language, meaning, explanation, keywords, source_id, status) values (${q(c.id)}, 'en', ${q(c.meaning)}, ${q(c.explanation)}, ${q(JSON.stringify(c.keywords))}::jsonb, 'veda-app-original', 'published');`);
  const sid = c.id + "-story";
  out.push(`insert into stories (id, title, text, illustration_idea) values (${q(sid)}, ${q(c.story.title)}, ${q(c.story.text)}, ${q(c.story.illustration?.idea)});`);
  out.push(`insert into verse_stories (verse_id, story_id) values (${q(c.id)}, ${q(sid)});`);
  out.push(`insert into teachings (verse_id, language, title, practice) values (${q(c.id)}, 'en', ${q(c.teaching.title)}, ${q(c.teaching.practice)});`);
  for (const t of c.test) out.push(`insert into quiz_questions (verse_id, question, options, answer_index) values (${q(c.id)}, ${q(t.question)}, ${arr(t.options)}, ${t.answer});`);
  for (const t of c.tags) tags.set(t, t[0].toUpperCase() + t.slice(1));
  out.push("");
}
// Full texts imported from digitised editions (content/import/*.json, made by scripts/import/*.py).
// Verses that already have a featured card keep their card; they only gain the imported translation and speaker.
// Every other verse is loaded as a draft, hidden from readers until reviewed and published.
// Sections can nest (Kanda > Sarga); a verse names its section by path, e.g. [2, 14].
const featured = new Set(cards.map((c) => c.id));
const importDir = root + "content/import/";
let imported = 0;
const sectionRef = (scripture, path) => {
  let ref = "null";
  path.forEach((n, i) => {
    ref = `(select id from sections where scripture_id = ${q(scripture)} and level = ${i + 1} and number = ${n} and parent_id ${i === 0 ? "is null" : "= " + ref})`;
  });
  return ref;
};
for (const f of readdirSync(importDir).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(readFileSync(importDir + f, "utf8"));
  const sc = data.scripture;
  out.push(`-- Imported: ${sc} (${f})`);
  for (const sec of data.sections ?? []) {
    const parent = sec.path.length > 1 ? sectionRef(sc, sec.path.slice(0, -1)) : "null";
    out.push(`insert into sections (scripture_id, parent_id, level, number, title, title_sanskrit, expected_verses) values (${q(sc)}, ${parent}, ${sec.path.length}, ${sec.path.at(-1)}, ${[sec.title, sec.title_sanskrit, sec.expected_verses].map(q).join(", ")}) on conflict do nothing;`);
  }
  // One multi-row insert per section keeps the seed small and fast.
  const groups = new Map();
  for (const v of data.verses) {
    const path = v.section_path ?? [v.chapter];
    if (featured.has(v.id)) {
      out.push(`update verses set speaker = ${q(v.speaker)} where id = ${q(v.id)};`);
      continue;
    }
    const key = path.join(".");
    if (!groups.has(key)) groups.set(key, { path, rows: [] });
    groups.get(key).rows.push(`(${[v.id, v.verse, v.reference, v.sanskrit, v.transliteration, v.speaker].map(q).join(", ")}, ${v.sort_key ?? v.chapter * 1000 + v.verse})`);
    imported++;
  }
  for (const { path, rows } of groups.values())
    out.push(`insert into verses (id, scripture_id, section_id, number, reference, sanskrit, transliteration, speaker, sort_key, is_featured, source_id, status)\nselect x.id, ${q(sc)}, ${sectionRef(sc, path)}, x.n, x.reference, x.sanskrit, x.transliteration, x.speaker, x.sort_key, false, ${q(data.sanskrit_source)}, 'draft'\nfrom (values\n${rows.join(",\n")}\n) as x(id, n, reference, sanskrit, transliteration, speaker, sort_key);`);
  const translations = data.verses.flatMap((v) =>
    Object.entries(v.translation).map(([lang, text]) => `(${[v.id, lang, text, data.translation_source[lang]].map(q).join(", ")}, ${!featured.has(v.id)})`)
  );
  if (translations.length)
    out.push(`insert into translations (verse_id, language, text, source_id, is_primary) values\n${translations.join(",\n")};`);
  out.push("");
}

out.splice(out.indexOf("") + 1, 0, ...[...tags].map(([id, label]) => `insert into tags (id, label) values (${q(id)}, ${q(label)});`));
for (const c of cards) for (const t of c.tags) out.push(`insert into verse_tags (verse_id, tag_id) values (${q(c.id)}, ${q(t)});`);
out.push("", "commit;", "");
writeFileSync(root + "supabase/seed.sql", out.join("\n"));
console.log(`Wrote supabase/seed.sql: ${catalogue.scriptures.length} scriptures, ${catalogue.sections.length} sections, ${cards.length} featured cards, ${imported} imported draft verses`);
