"""Import the Valmiki Ramayana (critical edition, 18,761 verses) into content/import/ramayana-<kanda>.json.

Sanskrit: GRETIL's Ramayana, text of the Baroda critical edition, input by Muneo Tokunaga,
revised by John Smith. Licence: CC BY-NC-SA 4.0 (see the source row in content/catalogue.json).
Devanagari is produced from the IAST by rule, so nothing is typed by hand.

No English yet: the public-domain translations (Griffith's verse rendering, Dutt's prose) follow
the older printed text and do not number individual verses, so they cannot be matched reliably.
Our own plain-English translation is a later step.

Run:
  pip install indic_transliteration
  python3 scripts/import/ramayana.py            # downloads into .cache/import/ramayana
  python3 scripts/import/ramayana.py --offline  # reuse the cached download
"""

import collections
import json
import os
import re
import sys
import urllib.request

from common import devanagari_verse

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CACHE = os.path.join(ROOT, ".cache", "import", "ramayana")
OUT = os.path.join(ROOT, "content", "import")
URL = "https://gretil.sub.uni-goettingen.de/gretil/corpustei/transformations/plaintext/sa_rAmAyaNa.txt"
UA = "VedaImport/0.1 (https://github.com/rahul-s-code/veda)"

KANDAS = [
    ("Bala Kanda", "बालकाण्ड"),
    ("Ayodhya Kanda", "अयोध्याकाण्ड"),
    ("Aranya Kanda", "अरण्यकाण्ड"),
    ("Kishkindha Kanda", "किष्किन्धाकाण्ड"),
    ("Sundara Kanda", "सुन्दरकाण्ड"),
    ("Yuddha Kanda", "युद्धकाण्ड"),
    ("Uttara Kanda", "उत्तरकाण्ड"),
]
# Verses per kanda in the critical edition, as a check on the download.
EXPECTED = [1941, 3160, 2060, 1987, 2487, 4436, 2690]
REF = re.compile(r"\s*R_(\d+),(\d+)\.(\d+)\s*$")


def main():
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "sa_rAmAyaNa.txt")
    if "--offline" not in sys.argv:
        print("Downloading GRETIL Ramayana...")
        req = urllib.request.Request(URL, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=120) as r:
            open(path, "wb").write(r.read())
    text = open(path, encoding="utf-8").read()
    if "Creative Commons Attribution-NonCommercial-ShareAlike 4.0" not in text:
        raise SystemExit("GRETIL's licence line changed; check it and update the source row before importing.")
    body = text.split("# Text", 1)[1]

    verses, lines = [], []
    for line in body.splitlines():
        line = line.strip()
        if not line:
            continue
        m = REF.search(line)
        lines.append(REF.sub("", line).strip())
        if m:
            k, s, v = map(int, m.groups())
            verses.append((k, s, v, lines))
            lines = []
    if lines:
        raise SystemExit(f"Text after the last verse reference: {lines}")

    seen = set()
    by_kanda = collections.defaultdict(list)
    for k, s, v, ls in verses:
        if (k, s, v) in seen:
            raise SystemExit(f"Duplicate verse {k}.{s}.{v}")
        if v >= 1000 or s >= 1000:
            raise SystemExit(f"Verse {k}.{s}.{v} does not fit the sort key")
        seen.add((k, s, v))
        by_kanda[k].append((s, v, ls))

    for k, (name, name_sa) in enumerate(KANDAS, start=1):
        rows = by_kanda[k]
        if len(rows) != EXPECTED[k - 1]:
            raise SystemExit(f"Kanda {k}: expected {EXPECTED[k - 1]} verses, found {len(rows)}")
        sargas = collections.Counter(s for s, _, _ in rows)
        for s, count in sargas.items():  # verses in each sarga must run 1..n with no gaps
            nums = sorted(v for ss, v, _ in rows if ss == s)
            if nums != list(range(1, count + 1)):
                raise SystemExit(f"Kanda {k} sarga {s}: verse numbers are not 1..{count}")
        data = {
            "scripture": "valmiki-ramayana",
            "sanskrit_source": "gretil-ramayana-ce",
            "translation_source": {},
            "notes": "Generated by scripts/import/ramayana.py. Do not edit by hand; fix the script or the source and re-run.",
            "sections": [{"path": [k], "title": name, "title_sanskrit": name_sa, "expected_verses": len(rows)}]
            + [{"path": [k, s], "title": f"Sarga {s}", "expected_verses": sargas[s]} for s in sorted(sargas)],
            "verses": [
                {
                    "id": f"ramayana-{k}-{s}-{v}",
                    "section_path": [k, s],
                    "verse": v,
                    "reference": f"{name}, Sarga {s}, Verse {v}",
                    "sort_key": k * 1_000_000 + s * 1000 + v,
                    "speaker": None,
                    "sanskrit": devanagari_verse(ls),
                    "transliteration": "\n".join(ls),
                    "translation": {},
                }
                for s, v, ls in rows
            ],
        }
        out = os.path.join(OUT, f"ramayana-{k}.json")
        with open(out, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
            f.write("\n")
        print(f"Wrote {os.path.relpath(out, ROOT)}: {len(rows)} verses in {len(sargas)} sargas")


if __name__ == "__main__":
    main()
